//! Writes `tests/reference.txt` (same format as `tests/cases.txt`): HMAC-SHA256
//! of pseudo-random keys (shorter and longer than the 64-byte block) and
//! messages, and the verification rules on tags of every length from 0 to 33,
//! with the expected results computed by the origin crate `hmac` 0.13.0 over
//! `sha2`.
//!
//!     cargo run --release --manifest-path tests/reference/Cargo.toml > tests/reference.txt

use hmac::{Hmac, KeyInit, Mac};
use sha2::Sha256;

struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        self.0 >> 33
    }
    fn bytes(&mut self, n: usize) -> Vec<u8> {
        (0..n).map(|_| self.next() as u8).collect()
    }
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{:02x}", x)).collect()
}

fn mac(key: &[u8], msg: &[u8]) -> Hmac<Sha256> {
    let mut m = <Hmac<Sha256> as KeyInit>::new_from_slice(key).unwrap();
    m.update(msg);
    m
}

fn word(ok: bool) -> &'static str {
    if ok { "ok" } else { "error" }
}

fn main() {
    println!("# Generated by tests/reference (hmac 0.13.0, sha2 0.11). Same format as cases.txt.");
    let mut g = Lcg(0x4d41_4331);
    for k in 0..300 {
        let kl = match k % 5 {
            0 => 64,
            1 => 65,
            2 => (g.next() % 64) as usize,
            _ => (g.next() % 200) as usize,
        };
        let key = g.bytes(kl);
        let ml = if k % 10 == 9 { (g.next() % 2000) as usize } else { (g.next() % 150) as usize };
        let msg = g.bytes(ml);
        let tag = mac(&key, &msg).finalize().into_bytes();
        println!("mac|{}|{}||{}", hex(&key), hex(&msg), hex(&tag));
    }
    // Every tag length from 0 to 33, the right bytes and with the last byte changed.
    let key = g.bytes(20);
    let msg = g.bytes(50);
    let tag = mac(&key, &msg).finalize().into_bytes();
    for n in 0..=33usize {
        let mut t: Vec<u8> = tag.iter().copied().cycle().take(n).collect();
        for t in [t.clone(), {
            if let Some(last) = t.last_mut() {
                *last ^= 1;
            }
            t
        }] {
            let s = mac(&key, &msg).verify_slice(&t).is_ok();
            let l = mac(&key, &msg).verify_truncated_left(&t).is_ok();
            println!("verify_slice|{}|{}|{}|{}", hex(&key), hex(&msg), hex(&t), word(s));
            println!("verify_truncated_left|{}|{}|{}|{}", hex(&key), hex(&msg), hex(&t), word(l));
        }
    }
}
