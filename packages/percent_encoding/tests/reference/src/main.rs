//! Writes `tests/reference.txt` (gotgan's case format, as `tests/cases.txt`)
//! with the expected values computed by the origin crate `percent-encoding`
//! 2.3.2: every byte value under both predefined sets and the named sets of
//! the driver, the membership of the named sets, and pseudo-random inputs for
//! encoding, decoding and the round trip.
//!
//!     cargo run --release --manifest-path tests/reference/Cargo.toml > tests/reference.txt

use percent_encoding::{percent_decode, percent_encode, AsciiSet, CONTROLS, NON_ALPHANUMERIC};

const EMPTY: &AsciiSet = &AsciiSet::EMPTY;
const ALL: &AsciiSet = &AsciiSet::EMPTY.complement();
const FRAGMENT: &AsciiSet = &CONTROLS.add(b' ').add(b'"').add(b'<').add(b'>').add(b'`');
const A_B: &AsciiSet = &AsciiSet::EMPTY.add(b'A').add(b'B');
const UNION_A_B: &AsciiSet = &AsciiSet::EMPTY.add(b'A').union(AsciiSet::EMPTY.add(b'B'));
const NOT_A_B: &AsciiSet = &AsciiSet::EMPTY.add(b'A').add(b'B').complement();
const NA_MINUS_DASH: &AsciiSet = &NON_ALPHANUMERIC.remove(b'-');

const SETS: &[(&str, &AsciiSet)] = &[
    ("empty", EMPTY),
    ("all", ALL),
    ("controls", CONTROLS),
    ("non_alphanumeric", NON_ALPHANUMERIC),
    ("fragment", FRAGMENT),
    ("a_b", A_B),
    ("union_a_b", UNION_A_B),
    ("not_a_b", NOT_A_B),
    ("na_minus_dash", NA_MINUS_DASH),
];

struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        self.0 >> 33
    }
}

/// Bytes in the case format: letters, digits and a few safe characters as
/// they are, every other byte as `\xHH`.
fn esc(b: &[u8]) -> String {
    let mut s = String::new();
    for &c in b {
        if c.is_ascii_alphanumeric() || b" %?<>-_.:;,=+*#".contains(&c) {
            s.push(c as char);
        } else {
            s.push_str(&format!("\\x{:02x}", c));
        }
    }
    s
}

fn enc(b: &[u8], set: &'static AsciiSet) -> String {
    percent_encode(b, set).to_string()
}

fn main() {
    println!("# Generated by tests/reference (percent-encoding 2.3.2). Same format as cases.txt.");
    let all: Vec<u8> = (0..=255).collect();
    for (name, set) in SETS {
        // Membership: an ASCII byte is in the set exactly when it is encoded.
        let bits: String = (0..128u8).map(|b| if enc(&[b], set) == (b as char).to_string() { '0' } else { '1' }).collect();
        println!("set {name}||{bits}");
        println!("encode {name}|{}|{}", esc(&all), esc(enc(&all, set).as_bytes()));
        if *name == "controls" || *name == "non_alphanumeric" {
            for b in 0..=255u8 {
                println!("encode {name}|{}|{}", esc(&[b]), esc(enc(&[b], set).as_bytes()));
            }
        }
    }
    // Every byte after %, and % before every pair of bytes from a small alphabet.
    for b in 0..=255u8 {
        let t = [b'%', b, b'0'];
        println!("decode|{}|{}", esc(&t), esc(&percent_decode(&t).collect::<Vec<u8>>()));
    }
    let alpha = b"%0aAfFgG ";
    for &x in alpha {
        for &y in alpha {
            let t = [b'%', x, y];
            println!("decode|{}|{}", esc(&t), esc(&percent_decode(&t).collect::<Vec<u8>>()));
        }
    }
    let mut g = Lcg(0x7065_7263);
    for k in 0..300 {
        let n = (g.next() % 60) as usize;
        let msg: Vec<u8> = (0..n).map(|_| g.next() as u8).collect();
        let (name, set) = SETS[k % SETS.len()];
        let e = enc(&msg, set);
        println!("encode {name}|{}|{}", esc(&msg), esc(e.as_bytes()));
        if set.add(b'%') == *set {
            let back: Vec<u8> = percent_decode(e.as_bytes()).collect();
            assert_eq!(back, msg);
            println!("round {name}|{}|{}", esc(&msg), esc(&back));
        }
        // Text that is mostly %-sequences, well formed or not.
        let pieces: &[&[u8]] = &[b"%", b"%2", b"%41", b"%4g", b"%zz", b"%FF", b"%ff", b"a", b"%%", b"%0"];
        let mut t: Vec<u8> = Vec::new();
        for _ in 0..(g.next() % 12) {
            t.extend_from_slice(pieces[(g.next() % pieces.len() as u64) as usize]);
        }
        println!("decode|{}|{}", esc(&t), esc(&percent_decode(&t).collect::<Vec<u8>>()));
    }
}
