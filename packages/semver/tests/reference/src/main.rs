//! Writes `tests/reference.txt` (gotgan's case format, as `tests/cases.txt`)
//! with the expected values computed by the origin crate `semver` 1.0.28:
//! the comparisons and requirements of the origin's tests whose exact result
//! the tests do not state (`from_tests.txt`, written when cases.txt was
//! transcribed), and pseudo-random versions, comparisons, requirements and
//! malformed text.
//!
//!     cargo run --release --manifest-path tests/reference/Cargo.toml > tests/reference.txt

use semver::{Comparator, Version, VersionReq};
use std::cmp::Ordering;

struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        self.0 >> 33
    }
    fn pick<'a>(&mut self, xs: &[&'a str]) -> &'a str {
        xs[(self.next() % xs.len() as u64) as usize]
    }
}

fn esc(s: &str) -> String {
    let mut o = String::new();
    for &c in s.as_bytes() {
        match c {
            b'\\' => o.push_str("\\\\"),
            b'|' => o.push_str("\\x7c"),
            0x20..=0x7e => o.push(c as char),
            _ => o.push_str(&format!("\\x{:02x}", c)),
        }
    }
    o
}

fn ord(o: Ordering) -> &'static str {
    match o {
        Ordering::Less => "<",
        Ordering::Equal => "=",
        Ordering::Greater => ">",
    }
}

fn parse_line(op: &str, text: &str) -> String {
    let out = match op {
        "version" => Version::parse(text).map(|v| v.to_string()),
        "req" => VersionReq::parse(text).map(|v| v.to_string()),
        "comparator" => Comparator::parse(text).map(|v| v.to_string()),
        _ => unreachable!(),
    };
    let out = match out {
        Ok(s) => s,
        Err(e) => format!("error: {e}"),
    };
    format!("{op}|{}|{}", esc(text), esc(&out))
}

fn cmp_lines(a: &str, b: &str) -> String {
    let x = Version::parse(a).unwrap();
    let y = Version::parse(b).unwrap();
    format!("cmp {a} {b}||{}\nprecedence {a} {b}||{}", ord(x.cmp(&y)), ord(x.cmp_precedence(&y)))
}

fn version(g: &mut Lcg) -> String {
    let nums = ["0", "1", "2", "3", "10", "11", "18446744073709551615"];
    let pre_ids = ["alpha", "beta", "rc", "0", "1", "2", "10", "11", "a1", "1a", "x-y", "-", "A", "Z"];
    let build_ids = ["001", "1", "01", "0", "sha", "5build", "a", "00", "10"];
    let mut s = format!("{}.{}.{}", g.pick(&nums), g.pick(&nums), g.pick(&nums));
    if g.next() % 2 == 0 {
        let n = 1 + g.next() % 3;
        let ids: Vec<&str> = (0..n).map(|_| g.pick(&pre_ids)).collect();
        s.push('-');
        s.push_str(&ids.join("."));
    }
    if g.next() % 3 == 0 {
        let n = 1 + g.next() % 2;
        let ids: Vec<&str> = (0..n).map(|_| g.pick(&build_ids)).collect();
        s.push('+');
        s.push_str(&ids.join("."));
    }
    s
}

fn main() {
    println!("# Generated by tests/reference (semver 1.0.28). Same format as cases.txt.");
    println!("# The comparisons and requirements of the origin's tests whose result the tests do not state.");
    for line in include_str!("../from_tests.txt").lines() {
        if let Some(r) = line.strip_prefix("REQ ") {
            println!("{}", parse_line("req", r));
        } else {
            let (a, b) = line.split_once(' ').unwrap();
            println!("{}", cmp_lines(a, b));
        }
    }
    println!("# Pseudo-random versions: printed back, compared, and matched against requirements.");
    let mut g = Lcg(0x5e3e_7e75);
    let vs: Vec<String> = (0..200).map(|_| version(&mut g)).collect();
    for v in &vs {
        println!("{}", parse_line("version", v));
    }
    for k in 0..400 {
        let a = &vs[(g.next() % vs.len() as u64) as usize];
        let b = if k % 5 == 0 { a.clone() } else { vs[(g.next() % vs.len() as u64) as usize].clone() };
        println!("{}", cmp_lines(a, &b));
    }
    let ops = ["", "=", ">", ">=", "<", "<=", "~", "^"];
    let parts = ["0", "1", "2", "*", "x"];
    for _ in 0..300 {
        let n = 1 + g.next() % 2;
        let mut req = String::new();
        for i in 0..n {
            if i > 0 {
                req.push_str(", ");
            }
            req.push_str(g.pick(&ops));
            req.push_str(g.pick(&["0", "1", "2"]));
            let depth = g.next() % 3;
            if depth >= 1 {
                req.push('.');
                req.push_str(g.pick(&parts));
            }
            if depth >= 2 {
                req.push('.');
                req.push_str(g.pick(&parts));
                if g.next() % 3 == 0 {
                    req.push('-');
                    req.push_str(g.pick(&["alpha", "beta.2", "0", "rc.1"]));
                }
            }
        }
        let line = parse_line("req", &req);
        println!("{line}");
        if let Ok(r) = VersionReq::parse(&req) {
            for _ in 0..3 {
                let v = &vs[(g.next() % vs.len() as u64) as usize];
                let x = Version::parse(v).unwrap();
                println!("matches {v}|{}|{}", esc(&req), r.matches(&x));
                if r.comparators.len() == 1 {
                    println!("matches_comparator {v}|{}|{}", esc(&req), r.comparators[0].matches(&x));
                }
            }
        }
    }
    println!("# Malformed text.");
    let bits = ["1", "0", "01", ".", "-", "+", "a", " ", "*", ">", "=", ",", "x", "\0", "é", "9999999999999999999999", "..", "-0", "+0"];
    for _ in 0..300 {
        let n = 1 + g.next() % 6;
        let t: String = (0..n).map(|_| g.pick(&bits)).collect();
        println!("{}", parse_line("version", &t));
        println!("{}", parse_line("req", &t));
        println!("{}", parse_line("comparator", &t));
    }
}
